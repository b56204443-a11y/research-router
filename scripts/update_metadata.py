#!/usr/bin/env python3
"""Regenerate distributed hashes and the human-readable module index."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def update(root: Path = ROOT) -> None:
    catalog_path = root / "skills/research-router/references/catalog.json"
    catalog = json.loads(catalog_path.read_text())
    catalog["module_count"] = len(catalog["modules"])
    catalog_path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")
    library = root / "skill-libraries/research-router"
    entries = []
    for m in catalog["modules"]:
        base = library / "modules" / m["folder"]
        entries.append({"folder": m["folder"], "source_repo": m["source_repo"],
                        "source_commit": m["source_commit"], "files": {
                            p.relative_to(base).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in sorted(base.rglob("*")) if p.is_file() and
                            "__pycache__" not in p.parts and p.suffix != ".pyc"}})
    snapshot_path = library / "provenance.json"
    snapshot = json.loads(snapshot_path.read_text()) if snapshot_path.exists() else {"schema_version": 1}
    snapshot["modules"] = entries
    snapshot_path.write_text(json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n")
    lines = ["# Module index / 模块目录", "", f"{len(entries)} modules. Generated by `scripts/update_metadata.py`.",
             "", "The router searches its compact catalog; this page is for people browsing the repository.", ""]
    for category in ["paper", "literature", "science", "artifact"]:
        members = sorted([m for m in catalog["modules"] if m["category"] == category], key=lambda m: m["name"])
        lines += [f"## {category} ({len(members)})", "", "| Module | Description | Source |", "|---|---|---|"]
        for m in members:
            path = f"../skill-libraries/research-router/modules/{m['folder']}/SKILL.md"
            description = m["description"].replace("|", "\\|").replace("\n", " ")
            lines.append(f"| [{m['name']}]({path}) | {description} | [{m['source_repo']}](https://github.com/{m['source_repo']}/tree/{m['source_commit']}) |")
        lines.append("")
    (root / "docs/MODULES.md").write_text("\n".join(lines) + "\n")
    print(f"Updated metadata for {len(entries)} modules; review changes before committing.")


if __name__ == "__main__":
    update()
